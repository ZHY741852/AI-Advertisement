    private fun videoForId(id: String): String =
        VIDEOS[id.hashCode().and(0x7FFFFFFF) % VIDEOS.size]

    // ================================================================
    //  数据入口
    // ================================================================

    private fun loadAds(channelKey: String): List<AdFeed> = when (channelKey) {
        AdChannel.ECOMMERCE.key -> ecommerceAds()
        AdChannel.HANGZHOU.key  -> hangzhouAds()
        AdChannel.FOOD.key      -> foodAds()
        AdChannel.TECH.key      -> techAds()
        AdChannel.TRAVEL.key    -> travelAds()
        AdChannel.FASHION.key   -> fashionAds()
        else                    -> featuredAds()
    }

    fun getAdFeeds(channelKey: String, page: Int, pageSize: Int): AdFeedList {
        val all = loadAds(channelKey)
        val from = (page - 1) * pageSize
        val to = minOf(from + pageSize, all.size)
        val items = if (from < all.size) all.subList(from, to) else emptyList()
        return AdFeedList(items, all.size, page, pageSize, to < all.size)
    }

    fun findAdById(adId: String): AdFeed? {
        AdChannel.values().forEach { ch ->
            loadAds(ch.key).find { it.id == adId }?.let { return it }
        }
        return null
    }

